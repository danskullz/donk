"""Generate a CS2 console config that teleports to Mirage retake positions and takes screenshots.

Phase 0 capture spike. Positions come from Valve's own maps/<map>_retake.txt. On Mirage those
positions are eye positions (about 60 units above the nav surface), so the player origin is
set 64 units lower. Writes the .cfg and a manifest describing what each shot should show.

usage: python -I make_capture_cfg.py <out_cfg> <out_manifest>
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from radar import open_pak01  # noqa: E402
from validate_projection import read_spawns  # noqa: E402

MAP = "de_mirage"
EYE_HEIGHT = 64.0
PICK = ["connector", "ct spawn", "market", "t spawn", "top of mid", "underpass", "window", "palace", "short/cat", "t aps"]
WAIT = 45  # frames between teleport and screenshot (about 0.4 s at 120 fps)


def main(out_cfg, out_manifest):
    spawns = read_spawns(open_pak01(), MAP)
    chosen = []
    for label in PICK:
        hit = next(s for s in spawns if s["title"] == label)
        chosen.append(hit)

    lines = [
        "// Generated by make_capture_cfg.py (Phase 0 capture spike, run 1). Quits when done.",
        "sv_cheats 1",
        "cl_drawhud 0",
        "map %s" % MAP,
        "wait 900",
        "sv_cheats 1",
        "bot_kick",
        "mp_freezetime 0",
        "mp_warmup_end",
        "noclip",
        "wait 180",
    ]
    manifest = {"map": MAP, "shots": []}

    def pose(s):
        return [
            "setpos %.3f %.3f %.3f" % (s["x"], s["y"], s["z"] - EYE_HEIGHT),
            "setang %.3f %.3f 0" % (s["pitch"], s["yaw"]),
            "wait %d" % WAIT,
        ]

    first = chosen[0]
    # experiment shots at one pose: HUD on, HUD off, HUD off + viewmodel command
    lines += ["cl_drawhud 1"] + pose(first) + ["screenshot", "wait 60"]
    manifest["shots"].append({"n": 1, "note": "baseline, HUD on", "pose": first})
    lines += ["cl_drawhud 0", "wait 30", "screenshot", "wait 60"]
    manifest["shots"].append({"n": 2, "note": "cl_drawhud 0", "pose": first})
    lines += ["r_drawviewmodel 0", "wait 30", "screenshot", "wait 60"]
    manifest["shots"].append({"n": 3, "note": "cl_drawhud 0 + r_drawviewmodel 0", "pose": first})
    # the ten requested positions
    for i, s in enumerate(chosen, start=4):
        lines += pose(s) + ["screenshot", "wait 60"]
        manifest["shots"].append({"n": i, "note": "retake position: " + s["title"], "pose": s})
    lines += ["wait 120", "quit", ""]

    with open(out_cfg, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    with open(out_manifest, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    print("wrote %d commands, %d shots" % (len(lines), len(manifest["shots"])))
    for shot in manifest["shots"]:
        p = shot["pose"]
        print("  %2d  %-34s eye=(%8.1f, %8.1f, %7.1f) pitch %6.1f yaw %7.1f" % (shot["n"], shot["note"], p["x"], p["y"], p["z"], p["pitch"], p["yaw"]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
